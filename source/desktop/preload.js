// Bridge between LocalPaint.html and the app: presets folder, .lp project files, importing files.
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('texpaintNative', {
  isApp: true,
  listPresets: () => ipcRenderer.invoke('presets:list'),
  readPreset: (p) => ipcRenderer.invoke('presets:read', p),
  writePreset: (name, data) => ipcRenderer.invoke('presets:write', name, data),
  openPresetsFolder: () => ipcRenderer.invoke('presets:open'),
  saveProject: (name, data, filePath, saveAs) => ipcRenderer.invoke('project:save', name, data, filePath, saveAs),
  openProject: () => ipcRenderer.invoke('project:open'),
  readProject: (p, autosave) => ipcRenderer.invoke('project:read', p, !!autosave),
  importFiles: () => ipcRenderer.invoke('file:import'),
  // Reimport mesh: where a dropped / picked model file lives, and reading it again from there.
  pathOf: (f) => { try { return webUtils.getPathForFile(f) || ''; } catch { return ''; } },
  readModel: (p) => ipcRenderer.invoke('model:read', p),
  pickModel: (near) => ipcRenderer.invoke('model:pick', near),
  onOpenPath: (cb) => ipcRenderer.on('project:open-path', (_e, p) => cb(p)),
  onCloseRequest: (cb) => ipcRenderer.on('app:close-request', () => cb()),
  ackClose: () => ipcRenderer.send('app:close-ack'),
  quit: () => ipcRenderer.send('app:quit'),
  autosaveWrite: (name, data, thumb, projectPath, keep) => ipcRenderer.invoke('autosave:write', name, data, thumb, projectPath, keep),
  autosaveList: () => ipcRenderer.invoke('autosave:list'),
  autosaveFolder: () => ipcRenderer.invoke('autosave:open-folder'),
  sessionStart: () => ipcRenderer.invoke('session:start'),
  recentList: () => ipcRenderer.invoke('recent:list'),
  recentAdd: (p, name, thumb) => ipcRenderer.invoke('recent:add', p, name, thumb),
  recentRemove: (p) => ipcRenderer.invoke('recent:remove', p),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  relaunch: () => ipcRenderer.invoke('app:relaunch'),
  openUrl: (url) => ipcRenderer.invoke('shell:open', url),
  cloudCatalog: (online) => ipcRenderer.invoke('cloud:catalog', online),
  cloudGet: (m) => ipcRenderer.invoke('cloud:get', m),
  sbsEngine: (custom) => ipcRenderer.invoke('sbs:engine', custom),
  sbsPick: () => ipcRenderer.invoke('sbs:pick'),
  sbsRender: (req) => ipcRenderer.invoke('sbs:render', req),
  sbsLibrary: () => ipcRenderer.invoke('sbs:library'),
  sbsRead: (p) => ipcRenderer.invoke('sbs:read', p),
  exportDefaultDir: () => ipcRenderer.invoke('export:defaultDir'),
  exportPickDir: (current) => ipcRenderer.invoke('export:pickDir', current),
  exportWrite: (dir, files) => ipcRenderer.invoke('export:write', dir, files),
  exportOpen: (dir) => ipcRenderer.invoke('export:open', dir),
  grungeCatalog: () => ipcRenderer.invoke('grunge:catalog'),
  grungeGet: (file) => ipcRenderer.invoke('grunge:get', file),
});
